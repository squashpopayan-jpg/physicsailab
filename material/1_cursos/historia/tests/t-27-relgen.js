module.exports = function (T, C, R) {
  const H = 'Histórico', S = 'SciPy', N = 'Numérico', K = C.K;
  for (const [eps, e, p] of R.gr_prec) T.abs(S, `precesión relativista integrada (RK4 vs DOP853), ε = ${eps}, e = ${e}`, C.grPrecession(eps, e), p, 2e-6);
  for (const [eps, e, p] of R.gr_prec) T.rel(N, `la integración reproduce 6πε a primer orden, ε = ${eps}`, C.grPrecession(eps, e), 6 * Math.PI * eps, 0.03);
  for (const [m, d] of R.gr_defl) T.abs(S, 'deflexión de la luz integrada (RK4 vs DOP853), m/b = ' + m, C.lightDeflectionNumeric(m), d, 2e-6);
  T.rel(N, 'la deflexión integrada tiende a 4m/b', C.lightDeflectionNumeric(1e-4), 4e-4, 2e-3);
  T.rel(S, 'perihelio de Mercurio: 42.98″ por siglo', C.perihelionPerCentury(C.GMSUN, 5.7909e10, 0.2056, 87.969), R.mercury, 1e-9);
  T.abs(H, 'Mercurio: 43″ por siglo (Le Verrier 1859: 38″; Einstein 1915: 43″)', R.mercury, 43, 0.05);
  T.abs(H, 'Venus: 8.6″ por siglo', C.perihelionPerCentury(C.GMSUN, 1.08208e11, 0.0068, 224.701), 8.6, 0.1);
  T.abs(H, 'Tierra: 3.8″ por siglo', C.perihelionPerCentury(C.GMSUN, 1.49598e11, 0.0167, 365.256), 3.84, 0.05);
  T.rel(S, 'deflexión de la luz rasante por el Sol (arcsec)', C.lightDeflection(C.GMSUN, 6.957e8) / C.ARCSEC, R.sun_defl, 1e-9);
  T.abs(H, 'Einstein 1915: 1.75″, el doble de la predicción newtoniana (0.87″)', C.lightDeflection(C.GMSUN, 6.957e8) / C.ARCSEC, 1.75, 0.01);
  T.abs(H, 'Soldner (1801) y Einstein (1911): 0.87″', C.lightDeflectionNewton(C.GMSUN, 6.957e8) / C.ARCSEC, 0.875, 0.01);
  T.rel(S, 'radio de Schwarzschild del Sol: 2.95 km', C.schwarzschild(1.98847e30), R.sun_rs, 1e-6);
  T.abs(H, 'Pound y Rebka (1959): 22.5 m dan 2.46×10⁻¹⁵', C.gravShift(9.80665, 22.5) * 1e15, 2.457, 0.01);
  const g = C.gpsDaily(26571e3);
  T.abs(S, 'GPS: efecto gravitacional (+45.7 µs/día)', g.grav, R.gps[0], 1e-6);
  T.abs(S, 'GPS: efecto de la velocidad (−7.2 µs/día)', g.spec, R.gps[1], 1e-6);
  T.abs(H, 'GPS: neto +38.5 µs/día; sin la corrección se acumularían 11 km de error al día', g.net, 38.5, 0.3);
  T.abs(H, 'GPS: 38 µs/día × c = 11.5 km al día', g.net * 1e-6 * K.c / 1e3, 11.5, 0.2);
  const Mc = C.chirpMass(36, 29);
  T.abs(S, 'GW150914: masa de chirrido ≈ 28 M☉', Mc, R.chirp.Mc, 1e-9);
  T.abs(H, 'GW150914: masa de chirrido de 28 M☉', Mc, 28, 0.6);
  const Mcs = Mc * 1.98847e30;
  T.abs(N, 'la frecuencia a 0.2 s de la fusión es ≈ 35 Hz (como en GW150914)', C.gwFreq(0.2, Mcs), 35, 2);
  T.abs(S, 'tiempo entre 35 y 250 Hz (integral de df/dt frente a la fórmula cerrada)', C.gwTimeToMerge(35, Mcs) - C.gwTimeToMerge(250, Mcs), R.chirp.t35_250, 1e-6);
  const e2 = C.ECLIPSE1919, w2 = C.weightedMean([e2[1].v, e2[2].v], [e2[1].s, e2[2].s]), w3 = C.weightedMean(e2.map((x) => x.v), e2.map((x) => x.s));
  T.abs(S, 'media ponderada de las dos placas aceptadas (numpy)', w2.mean, R.wmean2[0], 1e-12);
  T.abs(S, 'media ponderada con las tres (numpy)', w3.mean, R.wmean3[0], 1e-12);
  T.abs(S, 'χ² de las dos aceptadas frente a Einstein (1.75″)', C.chi2([e2[1].v, e2[2].v], [e2[1].s, e2[2].s], 1.75), R.chi2_gr_2, 1e-9);
  T.ok(H, 'las dos medidas aceptadas rechazan el valor newtoniano (0.87″) con χ² > 30', R.chi2_nw_2 > 30);
  T.ok(H, 'las placas aceptadas están más cerca de Einstein (1.75″) que de Newton (0.87″)', R.chi2_gr_2 < R.chi2_nw_2);
};
