/* Matriz para el enunciado: mt([[1, 2], [3, 4]]) → tabla con corchetes (ver estilos .mat). */
function mt(filas) {
  return '<table class="mat">' + filas.map(function (f) {
    return '<tr>' + f.map(function (c) { return '<td>' + String(c).replace(/^-/, '−') + '</td>'; }).join('') + '</tr>';
  }).join('') + '</table>';
}
