function circulo(r) { return [{ f: function (x) { return Math.sqrt(Math.max(0, r * r - x * x)); }, dom: [-r, r] }, { f: function (x) { return -Math.sqrt(Math.max(0, r * r - x * x)); }, dom: [-r, r] }]; }
function niveles(rs, etiquetas) {
  var cv = []; rs.forEach(function (r) { cv = cv.concat(circulo(r)); });
  return { curvas: cv, puntos: etiquetas || [] };
}
